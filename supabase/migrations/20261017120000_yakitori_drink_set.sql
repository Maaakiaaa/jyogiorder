-- 焼き鳥1品目 + ドリンクカテゴリから1品を選ぶセット。
-- ドリンクは複製せず、既存menu_itemsをカテゴリ参照する。
alter table menu_items
  add column if not exists is_set boolean not null default false,
  add column if not exists code integer;

update menu_items
set code = id
where code is null;

alter table menu_items
  alter column code set not null;
create unique index if not exists menu_items_code_idx on menu_items (code);

alter table options
  add column if not exists code integer;

update options
set code = id
where code is null;

alter table options
  alter column code set not null;
create unique index if not exists options_code_idx on options (code);

create table if not exists bundle_slots (
  id bigint generated by default as identity primary key,
  set_item_id bigint not null references menu_items(id) on delete cascade,
  name text not null,
  kind text not null check (kind in ('fixed', 'category')),
  fixed_item_id bigint references menu_items(id) on delete restrict,
  source_category_id bigint references categories(id) on delete restrict,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  check (
    (kind = 'fixed' and fixed_item_id is not null and source_category_id is null)
    or (kind = 'category' and fixed_item_id is null and source_category_id is not null)
  )
);

create unique index if not exists bundle_slots_set_item_name_idx on bundle_slots (set_item_id, name);
create index if not exists bundle_slots_set_item_id_idx on bundle_slots (set_item_id);

alter table order_items
  add column if not exists line_id text,
  add column if not exists parent_line_id text;
update order_items
set line_id = id::text
where line_id is null;
create index if not exists order_items_parent_line_id_idx on order_items (parent_line_id);
create unique index if not exists order_items_order_line_id_idx on order_items (order_id, line_id);

alter table bundle_slots enable row level security;
drop policy if exists "bundle_slots_select" on bundle_slots;
create policy "bundle_slots_select" on bundle_slots for select to anon, authenticated using (true);
drop policy if exists "bundle_slots_insert" on bundle_slots;
create policy "bundle_slots_insert" on bundle_slots for insert to anon, authenticated with check (true);
drop policy if exists "bundle_slots_update" on bundle_slots;
create policy "bundle_slots_update" on bundle_slots for update to anon, authenticated using (true) with check (true);

do $$
declare
  drink_category_id bigint;
  yakitori_item_id bigint;
  set_menu_item_id bigint;
  next_menu_code integer;
begin
  select id into drink_category_id from categories where name = 'ドリンク' order by id limit 1;
  if drink_category_id is null then
    insert into categories (name, sort_order) values ('ドリンク', 10)
    returning id into drink_category_id;
  end if;

  -- 既存のドリンクをカテゴリへ移動する。商品行はコピーしない。
  update menu_items
  set category_id = drink_category_id
  where name in ('コーラ', '水');

  select id into yakitori_item_id from menu_items where name = '焼き鳥' order by id limit 1;
  if yakitori_item_id is null then
    raise exception '焼き鳥のmenu_items行が見つかりません';
  end if;

  select id into set_menu_item_id from menu_items where name = '焼き鳥セット' order by id limit 1;
  if set_menu_item_id is null then
    select coalesce(max(code), 0) + 1 into next_menu_code from menu_items;
    insert into menu_items (category_id, name, price, code, is_set)
    values ((select id from categories where name = '通常メニュー' order by id limit 1), '焼き鳥セット', 300, next_menu_code, true)
    returning id into set_menu_item_id;
  else
    update menu_items set is_set = true where id = set_menu_item_id;
  end if;

  insert into bundle_slots (set_item_id, name, kind, fixed_item_id, display_order)
  values (set_menu_item_id, '焼き鳥', 'fixed', yakitori_item_id, 1)
  on conflict (set_item_id, name) do update
    set kind = excluded.kind, fixed_item_id = excluded.fixed_item_id,
        source_category_id = null, display_order = excluded.display_order;

  insert into bundle_slots (set_item_id, name, kind, source_category_id, display_order)
  values (set_menu_item_id, 'ドリンク', 'category', drink_category_id, 2)
  on conflict (set_item_id, name) do update
    set kind = excluded.kind, fixed_item_id = null,
        source_category_id = excluded.source_category_id, display_order = excluded.display_order;
end $$;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'bundle_slots'
  ) then
    alter publication supabase_realtime add table bundle_slots;
  end if;
end $$;
