-- 品目ごとの選択肢グループと選択肢。必須グループにはデフォルトを持たせず、
-- UI側で明示選択されるまでカート追加を許可しない。
create table if not exists option_groups (
  id bigint generated by default as identity primary key,
  menu_item_id bigint not null references menu_items(id) on delete cascade,
  name text not null,
  required boolean not null default false,
  display_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists options (
  id bigint generated by default as identity primary key,
  group_id bigint not null references option_groups(id) on delete cascade,
  name text not null,
  price_delta integer not null default 0,
  is_available boolean not null default true,
  is_active boolean not null default true,
  display_order integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists option_groups_menu_item_id_idx on option_groups (menu_item_id);
create index if not exists options_group_id_idx on options (group_id);

alter table order_items
  add column if not exists options_snapshot jsonb;

alter table option_groups enable row level security;
alter table options enable row level security;

drop policy if exists "option_groups_select" on option_groups;
create policy "option_groups_select" on option_groups for select to anon, authenticated using (true);
drop policy if exists "option_groups_insert" on option_groups;
create policy "option_groups_insert" on option_groups for insert to anon, authenticated with check (true);
drop policy if exists "option_groups_update" on option_groups;
create policy "option_groups_update" on option_groups for update to anon, authenticated using (true) with check (true);

drop policy if exists "options_select" on options;
create policy "options_select" on options for select to anon, authenticated using (true);
drop policy if exists "options_insert" on options;
create policy "options_insert" on options for insert to anon, authenticated with check (true);
drop policy if exists "options_update" on options;
create policy "options_update" on options for update to anon, authenticated using (true) with check (true);

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'option_groups'
  ) then
    alter publication supabase_realtime add table option_groups;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'options'
  ) then
    alter publication supabase_realtime add table options;
  end if;
end $$;
